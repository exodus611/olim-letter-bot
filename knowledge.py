def procedures_for_prompt() -> str:
    """Справочник процедур и сроков в текстовом виде — вставляется в системный промпт."""
    lines = []
    for org_id, o in ORGS.items():
        if not o["procedures"]:
            continue
        lines.append(f"[{org_id}] {o['name_ru']} ({o['name_he']}):")
        for p in o["procedures"]:
            lines.append(f"  - типы {', '.join(p['letter_types'])}: {p['rule']}")
    return "\n".join(lines)


def statutory_days(org_id: str, letter_type: str) -> int | None:
    """Законный срок в днях для пары (ведомство, тип письма), если известен."""
    org = ORGS.get(org_id)
    if not org:
        return None
    for p in org["procedures"]:
        if letter_type in p["letter_types"] and p.get("statutory_days"):
            return p["statutory_days"]
    return None


def contacts_block(org_id: str, letter_type: str) -> list[dict]:
    """Проверенные контакты для показа пользователю: сам орган + помощники."""
    org = ORGS.get(org_id) or ORGS["other"]
    out = []
    if org_id != "other":
        out.append({
            "kind": "org",
            "name": org["name_ru"],
            "phone": org["phone"],
            "hours": org["hours"],
            "languages": org["languages"],
            "site": org["site"],
            "online": org["online"],
        })
    helper_ids = HELPERS_BY_TYPE.get(letter_type, DEFAULT_HELPERS)
    for hid in helper_ids:
        h = UNIVERSAL_HELPERS[hid]
        out.append({"kind": "helper", **h})
    return out


def scam_note(org_id: str) -> str | None:
    org = ORGS.get(org_id)
    return org.get("scam_note") if org else None
